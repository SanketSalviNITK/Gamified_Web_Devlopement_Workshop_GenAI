// Builds the SQL that loads course lessons and quiz questions into the database.
//
//   node tools/build-course-seed.mjs            writes one seed migration per ready module (SEED_FILES)
//   node tools/build-course-seed.mjs --check    exits 1 if any of them is out of date (used by the tests)
//   node tools/build-course-seed.mjs --module m3 --out <file>   writes one module's seed somewhere else
//
// Sources: course/course.js (which lessons exist) and supabase/seed/quizzes/<module>.json.
// Each module has its own migration, so publishing a new module never edits an applied one.
// After changing an already-published module, write a new migration with --module/--out.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { MODULES } from '../course/course.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SEED_FILES = {
    m1: 'supabase/migrations/20261125000100_course_seed.sql',
    m2: 'supabase/migrations/20261125010000_course_seed_m2.sql',
    m3: 'supabase/migrations/20261125020000_course_seed_m3.sql',
    m4: 'supabase/migrations/20261126000000_course_seed_m4.sql',
};

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

export function loadQuiz(moduleId) {
    const file = join(root, 'supabase/seed/quizzes', `${moduleId}.json`);
    return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
}

export function buildSeed(onlyIds = null) {
    const lines = [
        '-- GENERATED by tools/build-course-seed.mjs from course/course.js and supabase/seed/quizzes/*.json.',
        '-- Do not edit by hand: change the sources and regenerate.',
        '',
    ];
    const ready = MODULES.filter((m) => m.ready && (!onlyIds || onlyIds.includes(m.id)));
    for (const m of ready) {
        lines.push(`-- ${m.id}: ${m.title}`);
        for (const l of m.lessons) {
            lines.push(`insert into public.course_lessons (id, module) values (${q(l.id)}, ${q(m.id)}) on conflict (id) do update set module = excluded.module;`);
        }
        const quiz = loadQuiz(m.id);
        if (!quiz) continue;
        const ids = [];
        for (const x of quiz.questions) {
            ids.push(x.id);
            lines.push(
                'insert into public.quiz_questions (id, module, kind, lesson, prompt, code, options, hint, answer, explanations, active) values (' +
                [q(x.id), q(m.id), q(x.kind), q(x.lesson), q(x.prompt), q(x.code ?? null), j(x.options), q(x.hint ?? null), j(x.answer), j(x.explanations), 'true'].join(', ') +
                ') on conflict (id) do update set module = excluded.module, kind = excluded.kind, lesson = excluded.lesson, prompt = excluded.prompt, code = excluded.code, ' +
                'options = excluded.options, hint = excluded.hint, answer = excluded.answer, explanations = excluded.explanations, active = true;'
            );
        }
        // Questions removed from the bank stay in the table (old answers refer to them) but are retired.
        lines.push(`update public.quiz_questions set active = false where module = ${q(m.id)} and id not in (${ids.map(q).join(', ')});`);
        lines.push('');
    }
    return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const args = process.argv.slice(2);
    const arg = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : null);
    const ready = MODULES.filter((m) => m.ready).map((m) => m.id);
    const jobs = arg('--module')
        ? [[arg('--module'), arg('--out') || join(root, SEED_FILES[arg('--module')] || '')]]
        : ready.map((id) => [id, SEED_FILES[id] ? join(root, SEED_FILES[id]) : null]);
    let stale = 0;
    for (const [id, out] of jobs) {
        if (!out) { console.error(`${id} has no seed file: add it to SEED_FILES in tools/build-course-seed.mjs`); stale++; continue; }
        const sql = buildSeed([id]);
        if (args.includes('--check')) {
            const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
            if (current !== sql) { console.error(`${out} is out of date. Run: node tools/build-course-seed.mjs`); stale++; }
        } else {
            writeFileSync(out, sql);
            console.log(`wrote ${out}`);
        }
    }
    if (stale) process.exit(1);
    if (args.includes('--check')) console.log('course seed is up to date');
}
