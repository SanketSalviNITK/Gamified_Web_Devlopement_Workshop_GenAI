// Builds the SQL that loads course lessons and quiz questions into the database.
//
//   node tools/build-course-seed.mjs            writes supabase/migrations/20261125000100_course_seed.sql
//   node tools/build-course-seed.mjs --check    exits 1 if that file is out of date (used by the tests)
//   node tools/build-course-seed.mjs --out <f>  writes somewhere else (e.g. a new migration after editing content)
//
// Sources: course/course.js (which lessons exist) and supabase/seed/quizzes/<module>.json.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { MODULES } from '../course/course.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUT = join(root, 'supabase/migrations/20261125000100_course_seed.sql');

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

export function loadQuiz(moduleId) {
    const file = join(root, 'supabase/seed/quizzes', `${moduleId}.json`);
    return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
}

export function buildSeed() {
    const lines = [
        '-- GENERATED by tools/build-course-seed.mjs from course/course.js and supabase/seed/quizzes/*.json.',
        '-- Do not edit by hand: change the sources and regenerate.',
        '',
    ];
    const ready = MODULES.filter((m) => m.ready);
    for (const m of ready) {
        lines.push(`-- ${m.id}: ${m.title}`);
        for (const l of m.lessons) {
            lines.push(`insert into public.course_lessons (id, module) values (${q(l.id)}, ${q(m.id)}) on conflict (id) do update set module = excluded.module;`);
        }
        const quiz = loadQuiz(m.id);
        if (!quiz) continue;
        const ids = [];
        for (const x of quiz.questions) {
            ids.push(x.id);
            lines.push(
                'insert into public.quiz_questions (id, module, kind, lesson, prompt, code, options, hint, answer, explanations, active) values (' +
                [q(x.id), q(m.id), q(x.kind), q(x.lesson), q(x.prompt), q(x.code ?? null), j(x.options), q(x.hint ?? null), j(x.answer), j(x.explanations), 'true'].join(', ') +
                ') on conflict (id) do update set module = excluded.module, kind = excluded.kind, lesson = excluded.lesson, prompt = excluded.prompt, code = excluded.code, ' +
                'options = excluded.options, hint = excluded.hint, answer = excluded.answer, explanations = excluded.explanations, active = true;'
            );
        }
        // Questions removed from the bank stay in the table (old answers refer to them) but are retired.
        lines.push(`update public.quiz_questions set active = false where module = ${q(m.id)} and id not in (${ids.map(q).join(', ')});`);
        lines.push('');
    }
    return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const args = process.argv.slice(2);
    const outIdx = args.indexOf('--out');
    const out = outIdx >= 0 ? args[outIdx + 1] : DEFAULT_OUT;
    const sql = buildSeed();
    if (args.includes('--check')) {
        const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
        if (current !== sql) {
            console.error(`${out} is out of date. Run: node tools/build-course-seed.mjs`);
            process.exit(1);
        }
        console.log('course seed is up to date');
    } else {
        writeFileSync(out, sql);
        console.log(`wrote ${out}`);
    }
}
